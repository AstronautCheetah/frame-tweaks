#!/usr/bin/env python3
"""dev/gen-compat.py: docs/compatibility.md, each tweak's status on each SteamOS and SteamVR build
it was checked on, from docs/compat/records.tsv (dev/update-check.sh record adds to it, on a Frame).

  dev/gen-compat.py          write docs/compatibility.md
  dev/gen-compat.py --check  fail if it isn't what the records give (dev/check.sh docs)
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RECORDS = ROOT / "docs/compat/records.tsv"
OUT = ROOT / "docs/compatibility.md"
FIELDS = ["date", "steamos", "build", "steamvr", "channel", "release", "mark", "tweak", "text"]
COLUMNS = 6         # (the newest builds; older ones stay in the records)
MARKS = {"✔": "works", "!": "needs attention", "⟳": "works after a SteamVR restart", "·": "not installed",
         "✘": "broken"}


def read(path=RECORDS):
    if not path.exists():
        return []
    with path.open(newline="") as f:
        rows = [dict(zip(FIELDS, r)) for r in csv.reader(f, delimiter="\t") if r and not r[0].startswith("#")]
    return [r for r in rows if len(r) == len(FIELDS)]


def render(rows):
    builds = []     # (steamos, build, steamvr), newest first by the date last checked
    for r in sorted(rows, key=lambda r: r["date"], reverse=True):
        b = (r["steamos"], r["build"], r["steamvr"])
        if b not in builds:
            builds.append(b)
    builds = builds[:COLUMNS]
    latest = {}     # (tweak, build) -> the newest record
    for r in sorted(rows, key=lambda r: r["date"]):
        latest[(r["tweak"], (r["steamos"], r["build"], r["steamvr"]))] = r
    tweaks = sorted({t for (t, b) in latest if b in builds})
    out = ["# Compatibility", "",
           "Each tweak's status on the SteamOS and SteamVR builds it was checked on, newest first. "
           "Generated by `dev/gen-compat.py` from [compat/records.tsv](compat/records.tsv); a "
           "maintainer adds records on a Frame with `dev/update-check.sh record` (CONTRIBUTING.md, "
           "\"Checking updates on a Frame\"). A build not listed hasn't been checked, which says "
           "nothing either way.", "",
           "Marks: " + "; ".join(f"{m} {w}" for m, w in MARKS.items()) + ".", ""]
    if not builds:
        return "\n".join(out + ["No records yet.", ""])
    head = ["Tweak"] + [f"SteamOS {s}<br>{b}<br>SteamVR {v or '?'}" for s, b, v in builds]
    out += ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    notes = []
    for t in tweaks:
        cells = []
        for b in builds:
            r = latest.get((t, b))
            cells.append(r["mark"] if r else "")
            if r and r["mark"] not in ("✔", "·"):
                notes.append(f"- **{t}** on SteamOS {b[0]} ({b[1]}): {r['text']}")
        out.append("| " + " | ".join([f"`{t}`"] + cells) + " |")
    if notes:
        out += ["", "## Notes", "", *notes]
    return "\n".join(out + [""])


def main(argv):
    text = render(read())
    if argv[1:] == ["--check"]:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("docs/compatibility.md is out of date: run dev/gen-compat.py")
        return
    if argv[1:]:
        sys.exit(__doc__)
    OUT.write_text(text)


if __name__ == "__main__":
    main(sys.argv)
